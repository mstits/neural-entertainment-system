def test_the_whole_cohort_is_declined_and_every_refusal_names_its_numbers() -> None:
    """The roster fact this commit actually ships.

    Every cohort profile that carried the 2026-08-26 arming must now be
    disarmed, and each refusal must carry that profile's OWN measurement
    -- not a shared sentence. A blanket disarm with one boilerplate reason
    would be indistinguishable from giving up."""
    reasons, roms = {}, {}
    for p in cohort():
        prof = yaml.safe_load(p.read_text())
        blk = ((((prof.get("solve") or {}).get("clear") or {})
                .get("signals") or {}).get("scene_cut") or {})
        if blk.get("enabled") is False:
            reasons[p.stem] = blk.get("reason") or ""
            roms[p.stem] = (prof.get("solve") or {}).get("rom")
    assert len(reasons) >= 23, (
        f"only {len(reasons)} profiles carry an explicit scene_cut refusal; "
        "the 2026-08-26 arming covered 23")

    # Two profiles may share a refusal ONLY when they are two profiles of
    # the same ROM measured identically -- `metroid` and `metroid_roomfp`
    # are that case and an identical measurement earning an identical
    # sentence is correct. Any other repeat is boilerplate.
    by_reason: dict[str, list[str]] = {}
    for n, r in reasons.items():
        by_reason.setdefault(r, []).append(n)
    shared = {r: ns for r, ns in by_reason.items() if len(ns) > 1}
    for r, ns in shared.items():
        assert len({roms[n] for n in ns}) == 1, (
            f"{sorted(ns)} share a refusal reason verbatim but are different "
            "games -- a refusal that is not about the profile is not a "
            "measurement")
    assert len(by_reason) >= len(reasons) - 1, (
        f"{len(reasons)} refusals collapse to only {len(by_reason)} distinct "
        "sentences")

    for n, r in reasons.items():
        assert "scene_cut_arming.py" in r, n
        assert any(ch.isdigit() for ch in r), (
            f"{n}: refusal carries no number at all")
        # ...and the numbers must be THIS profile's own blank-channel
        # measurement -- the channel the refusal is about. Every refusal
        # quotes either the gate it is refusing, that gate's null, or the
        # run count that made the channel dead.
        assert any(k in r for k in ("blank_min=", "max d_blank=",
                                    "odo_blank produced")), n


