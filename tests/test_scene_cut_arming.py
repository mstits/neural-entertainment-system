def test_every_armed_profile_passes_every_clause() -> None:
    """The roster fact 4dd15ea had no test for."""
    survey = _survey()
    # NOT `_audit()`: that skips when the receipt is absent, and a skip
    # here would mean an arming with no measurement behind it sails
    # through. An absent receipt makes C6 report `ok: False` with a
    # reason, which is the same rule C1 follows for an absent survey
    # record -- a missing measurement is not a passing one.
    audit = ((json.loads(RECEIPT.read_text()) or {}).get("profiles") or {}
             ) if RECEIPT.exists() else {}
    bad = {}
    for p in _armed_paths():
        prof = yaml.safe_load(p.read_text())
        banked = (audit.get(p.stem) or {}).get("measured")
        failed = [c for c in static_clauses(p.stem, prof, survey.get(p.stem), p,
                                            banked=banked)
                  if not c["ok"]]
        if failed:
            bad[p.stem] = [(c["clause"], c["detail"]) for c in failed]
    assert not bad, (
        "these profiles arm scene_cut against their own recorded evidence:\n"
        + json.dumps(bad, indent=1))


