def test_an_armed_gate_clears_its_veto_INDEPENDENT_null() -> None:
    """C6 on the roster, and the one the test above is NOT a substitute
    for.

    `null_max_d_blank` excludes every window the death veto covered, so a
    gate can read "above its null" while sitting an order of magnitude
    under the death fades that null was computed by deleting. That is the
    shape `gradius` shipped in: `blank_min: 1` against a vetoed-out null
    of 0 and a veto covering 87.5% of all windows.

    The probe that produced these numbers cleared nothing, so its ENTIRE
    (d_scene, d_blank) distribution is null and the gate has to clear the
    whole of it on its own. The death veto is then a second guard rather
    than the only one -- which is the difference between a defence and a
    single point of failure."""
    rows = _audit()
    bad = {}
    for n, r in rows.items():
        m = r.get("measured") or {}
        g = m.get("gate")
        if not g:
            continue
        assert "null_max_d_blank_all" in m, (
            f"{n}: the receipt carries no veto-independent null, so C6 "
            "cannot be evaluated and must not be assumed")
        if int(g["blank_min"]) <= int(m["null_max_d_blank_all"]):
            bad[n] = (f"blank_min={g['blank_min']} <= veto-independent null "
                      f"{m['null_max_d_blank_all']}")
        elif int(g["scene_min"]) <= int(m["null_max_d_scene_all"]):
            bad[n] = (f"scene_min={g['scene_min']} <= veto-independent null "
                      f"{m['null_max_d_scene_all']}")
    assert not bad, json.dumps(bad, indent=1)


def test_the_disarm_had_evidence_and_the_evidence_is_committed() -> None:
    """THE ANTI-VACUITY TEST FOR THE DISARM ITSELF.

    After this commit no cohort profile arms `scene_cut`, so every
    residual assertion above iterates an EMPTY set and passes for free.
    That is exactly the shape this campaign is named after, so the
    evidence the decision rested on is committed too: the same audit, at
    the same budget and seed, run against the 2026-08-26 arming before it
    was taken down.

    What this reports if the mechanism is absent: a missing or empty
    as-found receipt fails here rather than skipping, because "we disarmed
    23 profiles" with no measurement behind it is a judgement wearing a
    measurement's clothes -- which is the exact criticism that produced
    this commit."""
    assert ASFOUND.exists(), (
        f"the as-found measurement is missing: {ASFOUND}. The disarm of 23 "
        "profiles has no committed evidence, so nothing distinguishes it "
        "from giving up")
    rows = (json.loads(ASFOUND.read_text()) or {}).get("profiles") or {}
    armed = {n: r["measured"] for n, r in rows.items()
             if (r.get("measured") or {}).get("armed")}
    assert len(armed) == 23, (
        f"the as-found receipt describes {len(armed)} armed profiles; "
        "4dd15ea armed 23")
    firing = {n: m["residual_triggers"] for n, m in armed.items()
              if m.get("residual_triggers")}
    assert len(firing) >= 10, (
        "the as-found receipt no longer shows the armed gates firing on "
        "non-clearing play, which is the finding the disarm rests on: "
        + json.dumps(firing))
    # ...and the refusals must not depend on the veto-independent null
    # being the number used: every firing gate is also at or below its
    # WEAKER, vetoed-out null, so C6's verdict here is robust to which
    # null you pick.
    fragile = {n: (armed[n]["gate"]["blank_min"],
                   armed[n]["null_max_d_blank"],
                   armed[n]["null_max_d_blank_all"])
               for n in firing
               if armed[n]["gate"]["blank_min"] > armed[n]["null_max_d_blank"]}
    assert not fragile, (
        "some firing gate clears the vetoed-out null and is refused only by "
        "the veto-independent one -- report that rather than asserting it "
        "away: " + json.dumps(fragile))


def test_the_two_nulls_hold_their_invariant_and_the_veto_shaves_almost_nothing() -> None:
    """What the veto's coverage is actually worth, measured.

    `null_max_d_blank_all` counts every window; `null_max_d_blank` drops
    the ones the death veto covered. The first can never be SMALLER --
    that is a structural invariant of NullTracker and a violation means
    the tracker is miscounting, not that the roster changed.

    The measured finding underneath it: on the blank channel -- the
    channel every one of these gates actually votes with -- the veto
    barely moves the number, because SceneCutSignal's window is 240
    observations while the veto's transient is a handful. A fade's blank
    movement is still inside the rolling buffer long after `dying` has
    cleared and lands in a non-vetoed window anyway. So "the debounced
    death veto is what keeps this armed signal from mistaking a respawn
    for a transition", the sentence six 2026-08-26 configs shipped, was
    not true of the blank channel.

    Whether that shave ever changes an arming verdict is asserted
    separately, by the `fragile` check in
    `test_the_disarm_had_evidence_and_the_evidence_is_committed`."""
    if not ASFOUND.exists():
        pytest.skip(f"as-found receipt absent: {ASFOUND}")
    rows = (json.loads(ASFOUND.read_text()) or {}).get("profiles") or {}
    seen = 0
    for n, r in rows.items():
        m = r.get("measured") or {}
        if m.get("unmeasurable") or m.get("n_blank_runs") is None:
            continue
        seen += 1
        assert m["null_max_d_blank_all"] >= m["null_max_d_blank"], (
            f"{n}: the veto-independent null is SMALLER than the vetoed-out "
            "one, which is impossible -- NullTracker is miscounting")
        assert m["null_max_d_scene_all"] >= m["null_max_d_scene"], n
    assert seen >= 20, f"only {seen} profiles carry a null measurement"


def test_c6_catches_at_least_one_gate_the_older_null_rule_would_pass() -> None:
    """C6 EARNS ITS PLACE ON THE REAL ROSTER, not only on a fixture.

    `test_the_policy_can_still_fail` proves C6 refuses a synthetic gate
    under a synthetic null. That is necessary and not sufficient: a clause
    that never separates from the clause it supersedes is decoration. So
    this demands a REAL profile in the as-found receipt that

        passes the older rule  (gate > vetoed-out null), and
        fails C6              (gate <= veto-independent null)

    -- i.e. a gate whose residual reads 0 only because the death veto
    covered every window that would have fired it. `megaman` is that case:
    vetoed-out null (0, 0), veto-independent null (2, 18), gate
    blank_min 1, residual 0. If no such profile exists the two rules agree
    everywhere and C6 should be reported as inert rather than kept as if
    it were load-bearing."""
    if not ASFOUND.exists():
        pytest.skip(f"as-found receipt absent: {ASFOUND}")
    rows = (json.loads(ASFOUND.read_text()) or {}).get("profiles") or {}
    separated = {}
    for n, r in rows.items():
        m = r.get("measured") or {}
        g = m.get("gate")
        if not g or m.get("unmeasurable"):
            continue
        old_ok = (int(g["blank_min"]) > int(m["null_max_d_blank"])
                  and int(g["scene_min"]) > int(m["null_max_d_scene"]))
        new_ok = (int(g["blank_min"]) > int(m["null_max_d_blank_all"])
                  and int(g["scene_min"]) > int(m["null_max_d_scene_all"]))
        if old_ok and not new_ok:
            separated[n] = {"gate": g,
                            "null_vetoed": [m["null_max_d_scene"],
                                            m["null_max_d_blank"]],
                            "null_all": [m["null_max_d_scene_all"],
                                         m["null_max_d_blank_all"]],
                            "residual": m["residual_triggers"]}
    assert separated, (
        "no armed gate on the real roster is refused by C6 while passing the "
        "vetoed-out null rule -- on this data C6 is inert and must be "
        "reported as such, not carried as a load-bearing clause")


