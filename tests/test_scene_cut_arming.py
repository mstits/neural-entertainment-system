def test_the_policy_can_still_fail() -> None:
    """Each clause, driven over a profile built to violate exactly it.

    This is the mutation harness in test form: replace any one clause's
    verdict with a constant True and the matching case below stops
    refusing. Without this test the roster assertions would pass just as
    happily over a policy that never refuses anything."""
    def prof(**over):
        cfg = {"scene_min": 6, "blank_min": 1, "kind": ["fade"],
               "death_debounce": 3}
        cfg.update(over.pop("cfg", {}))
        solve = {"progress": {"source": "odometer"}, "lives": 0x0100,
                 "clear": {"signals": {"scene_cut": cfg}}}
        solve.update(over)
        return {"solve": solve}

    live = {"n_blank_runs": 7, "n_scene_runs": 3,
            "has_non_death_candidate": True}

    def verdicts(name, p, sv, path=None):
        return {c["clause"]: c["ok"] for c in static_clauses(name, p, sv, path)}

    # C1 -- blank-only arm over a blank counter measured at zero.
    dead = dict(live, n_blank_runs=0)
    assert verdicts("x", prof(), dead)["C1_CHANNEL_ALIVE"] is False
    assert verdicts("x", prof(), live)["C1_CHANNEL_ALIVE"] is True
    # ...and a scene-gating arm survives a dead BLANK channel only because
    # its own channel moved, which is the asymmetry C1 has to get right.
    pan = prof(cfg={"kind": ["pan", "warp", "fade"]})
    assert verdicts("x", pan, dead)["C1_CHANNEL_ALIVE"] is True

    # C2 -- no lives byte at all, and a measured-false one.
    assert verdicts("x", prof(lives=0), live)["C2_VALIDATED_LIVES"] is False
    assert verdicts("x", prof(lives=None), live)["C2_VALIDATED_LIVES"] is False
    name, addr = next(iter(FALSIFIED_LIVES))
    assert verdicts(name, prof(lives=addr), live)["C2_VALIDATED_LIVES"] is False
    # ...the SAME address on a different profile is not condemned: the
    # falsification is a measurement about one game's byte, not a global
    # blacklist of an integer.
    assert verdicts("other", prof(lives=addr), live)["C2_VALIDATED_LIVES"] is True
    # ...and no veto declared means nothing to validate.
    novet = prof(lives=0, cfg={"death_debounce": None})
    novet["solve"]["clear"]["signals"]["scene_cut"].pop("death_debounce")
    assert verdicts("x", novet, live)["C2_VALIDATED_LIVES"] is True

    # C3 -- an all-death-class population with no disclosure in the file.
    deathonly = dict(live, has_non_death_candidate=False)
    v = verdicts("x", prof(), deathonly, None)
    assert v["C3_SEPARABILITY_DISCLOSED"] is False
    assert "C3_SEPARABILITY_DISCLOSED" not in verdicts("x", prof(), live)

    # C5 -- the seam floor.
    assert verdicts("x", prof(cfg={"scene_min": 1}),
                    live)["C5_SCENE_MIN_ABOVE_SEAM"] is False
    assert verdicts("x", prof(cfg={"scene_min": 2}),
                    live)["C5_SCENE_MIN_ABOVE_SEAM"] is True

    # C6 -- the gate against the VETO-INDEPENDENT null. This is the
    # gradius shape: a blank_min of 1 under a measured null of 36, whose
    # residual reads 0 only because the death veto covered the windows
    # that would have fired.
    def c6(cfg, banked):
        return {c["clause"]: c["ok"] for c in
                static_clauses("x", prof(cfg=cfg), live, None,
                               banked=banked)}["C6_GATE_ABOVE_FULL_NULL"]

    null36 = {"null_max_d_blank_all": 36, "null_max_d_scene_all": 0,
              "null_max_d_blank": 0, "null_max_d_scene": 0,
              "n_rollouts": 4, "steps_per_rollout": 6000}
    assert c6({"blank_min": 1}, null36) is False, (
        "a gate under its own null must be refused even when the vetoed-out "
        "null reads 0 -- that zero is the veto's number, not the gate's")
    assert c6({"blank_min": 37}, null36) is True
    assert c6({"blank_min": 36}, null36) is False, "at the null is not above it"
    # ...and the scene half of the same clause.
    assert c6({"scene_min": 6, "blank_min": 37},
              dict(null36, null_max_d_scene_all=6)) is False
    # A missing measurement is not a passing one, exactly as with C1.
    assert c6({"blank_min": 999}, None) is False


