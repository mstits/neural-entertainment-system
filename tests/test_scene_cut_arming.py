"""The ARMING DECISION gets a test, which is the gap 4dd15ea shipped through.

On 2026-08-26, 23 profiles were armed with `solve.clear.signals.scene_cut`
off a survey whose script was never committed. Every scene_cut test in the
suite that day drove a SYNTHETIC profile built by a local `_profile(...)`
helper, so nothing in code read the real `configs/*.yaml` and nothing could
have failed when:

  * four profiles armed `kind: [fade]` -- a blank-only gate -- on a blank
    counter measured at ZERO runs in 12,000 steps. `tetris_usa` was
    DECLINED on that exact evidence.
  * `darkwing_duck` armed `death_debounce: 3` over `lives: 0`, an admitted
    placeholder the survey itself recorded as `have_lives: false`, so the
    veto debounced RAM[0x0000].
  * `ninja_gaiden` armed the same veto over `lives: 0x001F`, which
    docs/research/FALSE_DEATH_FANOUT_2026-08-26.md measures the SAME DAY
    as a 0<->255 flicker artifact.
  * ten profiles armed `scene_min: 1`, which SceneCutSignal's own
    docstring forbids in writing.
  * seven profiles armed `blank_min: 1` while every blank run their own
    survey observed was a death fade 5-9 steps long -- the gate sat an
    order of magnitude BELOW its own null and the death veto was the
    only thing holding it shut. On `gradius` that veto was covering
    87.5% of every window, so its "residual 0" was a property of the
    veto and not of the gate at all.

WHAT THESE TESTS REPORT WHEN THE MECHANISM IS ABSENT (the binding
anti-vacuity question, answered in code):

  * `test_every_armed_profile_passes_every_clause` reads the REAL config
    files. If the arming policy were deleted -- every clause returning ok
    -- `test_the_policy_can_still_fail` fails, because it drives the same
    clauses over profiles constructed to violate each one and demands a
    refusal.
  * `test_the_committed_audit_covers_exactly_the_armed_set` fails if the
    receipt drifts from the configs in EITHER direction, so an arming
    added without re-running the audit is caught even though the test
    itself runs no emulator.
  * the residual assertions read `residual_triggers` from the audit
    receipt. A profile whose odometer is dead also reports 0 there, which
    is why C1 is a separate clause over the RAW run counts and is asserted
    separately -- a passing residual alone is never taken as health.

WHAT THE MEASUREMENT DECIDED (2026-08-27). Re-run as a measurement rather
than a judgement, the arming does not survive: **14 of the 23 armed gates
fire on play that cleared nothing**, up to 207 false positives on one
profile. All 23 are now disarmed with `enabled: false` and a per-profile
measured reason, and the cohort is back at quorum UNREACHABLE where it was
before 4dd15ea.

That creates a vacuity risk of its own, which is why there are two
receipts. With nothing armed, every residual assertion below iterates an
EMPTY set and passes for free. So the evidence the disarm rests on is
committed as well -- the same audit, same budget, same seed, run against
the 2026-08-26 arming before it was taken down -- and
`test_the_disarm_had_evidence_and_the_evidence_is_committed` fails rather
than skips if it goes missing.

None of this needs a ROM: the expensive half (`--audit`) is banked in
docs/receipts/clear_control/scene_cut_arming_2026-08-27.json (as shipped)
and scene_cut_arming_asfound_2026-08-27.json (as found), regenerated by
`scripts/scene_cut_arming.py --audit`.
"""
